#!/usr/bin/env node
/**
 * Generates supabase/seed/02_store_demo_cart_checkout.sql (applied by `npm run seed:logistics`)
 * from scripts/data/logistics-demo.json.
 *
 * Usage:
 *   node scripts/generate-cart-checkout-seed.mjs [output-path]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const snapshotPath = join(root, "scripts/data/logistics-demo.json");
const defaultOut = join(root, "supabase/seed/02_store_demo_cart_checkout.sql");
const outPath = resolve(process.argv[2] ?? defaultOut);

const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8"));

const hash = (seed) => {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i += 1) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
};

const sqlNum = (value) => {
  if (value == null || value === "") return "null";
  const n = Number(value);
  if (!Number.isFinite(n)) return "null";
  return String(n);
};

const sqlBool = (value) => (value ? "true" : "false");

const sqlText = (value) => `'${String(value).replaceAll("'", "''")}'`;

const lines = [];
lines.push("-- Generated by scripts/generate-cart-checkout-seed.mjs — do not edit by hand.");
lines.push("-- Logistics, containers, Supply costs, plant backfill.");
lines.push("");
lines.push("begin;");
lines.push("");

// ---------------------------------------------------------------------------
// Containers
// ---------------------------------------------------------------------------
lines.push("-- Container types from logistics-demo.json");
for (const [index, container] of snapshot.containers.entries()) {
  lines.push(`insert into public.store_container_type (
  code, name, inner_length_mm, inner_width_mm, inner_height_mm, max_weight_kg, sort_order
) values (
  ${sqlText(container.code)},
  ${sqlText(container.name)},
  ${sqlNum(container.inner_length)},
  ${sqlNum(container.inner_width)},
  ${sqlNum(container.inner_height)},
  ${sqlNum(container.max_weight)},
  ${index + 1}
) on conflict (code) do update set
  name = excluded.name,
  inner_length_mm = excluded.inner_length_mm,
  inner_width_mm = excluded.inner_width_mm,
  inner_height_mm = excluded.inner_height_mm,
  max_weight_kg = excluded.max_weight_kg,
  sort_order = excluded.sort_order;`);
}
lines.push("");

// ---------------------------------------------------------------------------
// Variant logistics (+ quantity_per_unit) — product logistics copied to variants
// ---------------------------------------------------------------------------
lines.push("-- Quantity per unit + logistics for every variant (extra variants copy product logistics)");
lines.push(`do $seed$
declare
  r record;
  v_length numeric;
  v_width numeric;
  v_height numeric;
  v_weight numeric;
  v_stacking boolean;
  v_stacking_limit integer;
  v_rotate_length boolean;
  v_rotate_width boolean;
  v_max_per_container integer;
  v_qty integer;
  v_source text;
begin
  for r in
    select v.id as variant_id, v.product_id
    from public.store_product_variant v
    where v.deleted_at is null
  loop`);

lines.push(`    select
      l.quantity_per_unit,
      l.length_cm,
      l.width_cm,
      l.height_cm,
      l.weight_kg,
      l.stacking,
      l.stacking_limit,
      l.rotate_length,
      l.rotate_width,
      l.max_per_container,
      l.source
    into
      v_qty, v_length, v_width, v_height, v_weight,
      v_stacking, v_stacking_limit, v_rotate_length, v_rotate_width,
      v_max_per_container, v_source
    from (values`);

const sanitizeLogistics = (raw) => {
  const length = Number(raw?.length);
  const width = Number(raw?.width);
  const height = Number(raw?.height);
  const weight = Number(raw?.weight);
  const qty = Number(raw?.quantity_per_unit);
  const sane =
    Number.isFinite(length) &&
    length > 0 &&
    length < 1000 &&
    Number.isFinite(width) &&
    width > 0 &&
    width < 1000 &&
    Number.isFinite(height) &&
    height > 0 &&
    height < 1000 &&
    Number.isFinite(weight) &&
    weight > 0;
  if (!sane) {
    return {
      quantity_per_unit: 1,
      length: 100,
      width: 50,
      height: 50,
      weight: 50,
      stacking: true,
      stacking_limit: null,
      rotate_length: false,
      rotate_width: false,
      max_per_container: null,
      source: "estimated",
    };
  }
  return {
    quantity_per_unit: Number.isFinite(qty) && qty > 0 && qty <= 100 ? Math.round(qty) : 1,
    length,
    width,
    height,
    weight,
    stacking: Boolean(raw.stacking),
    stacking_limit: raw.stacking_limit == null ? null : Number(raw.stacking_limit),
    rotate_length: Boolean(raw.rotate_length),
    rotate_width: Boolean(raw.rotate_width),
    max_per_container: raw.max_per_container == null ? null : Number(raw.max_per_container),
    source: raw.source === "prod" ? "prod" : "estimated",
  };
};

// seed:logistics creates store_product rows in snapshot order after `restart identity`, so the
// database id is the snapshot position, not the snapshot `id`.
const valueRows = [];
for (const [index, product] of snapshot.products.entries()) {
  const L = sanitizeLogistics(product.logistics);
  valueRows.push(`      (${index + 1}, ${sqlNum(L.quantity_per_unit)}, ${sqlNum(L.length)}, ${sqlNum(L.width)}, ${sqlNum(L.height)}, ${sqlNum(L.weight)}, ${sqlBool(Boolean(L.stacking))}, ${sqlNum(L.stacking_limit)}, ${sqlBool(Boolean(L.rotate_length))}, ${sqlBool(Boolean(L.rotate_width))}, ${sqlNum(L.max_per_container)}, ${sqlText(L.source)})`);
}
lines.push(valueRows.join(",\n"));
lines.push(`    ) as l(
      product_id, quantity_per_unit, length_cm, width_cm, height_cm, weight_kg,
      stacking, stacking_limit, rotate_length, rotate_width, max_per_container, source
    )
    where l.product_id = r.product_id;

    if not found then
      -- Fallback for products missing from snapshot
      v_qty := 1;
      v_length := 100;
      v_width := 50;
      v_height := 50;
      v_weight := 50;
      v_stacking := true;
      v_stacking_limit := null;
      v_rotate_length := false;
      v_rotate_width := false;
      v_max_per_container := null;
      v_source := 'estimated';
    end if;

    update public.store_product_variant
    set quantity_per_unit = coalesce(nullif(v_qty, 0), 1)
    where id = r.variant_id;

    insert into public.store_product_variant_logistics (
      product_variant_id, length_cm, width_cm, height_cm, weight_kg,
      stacking, stacking_limit, rotate_length, rotate_width, max_per_container, source
    ) values (
      r.variant_id, v_length, v_width, v_height, v_weight,
      v_stacking, v_stacking_limit, v_rotate_length, v_rotate_width, v_max_per_container, v_source
    ) on conflict (product_variant_id) do update set
      length_cm = excluded.length_cm,
      width_cm = excluded.width_cm,
      height_cm = excluded.height_cm,
      weight_kg = excluded.weight_kg,
      stacking = excluded.stacking,
      stacking_limit = excluded.stacking_limit,
      rotate_length = excluded.rotate_length,
      rotate_width = excluded.rotate_width,
      max_per_container = excluded.max_per_container,
      source = excluded.source;
  end loop;
end;
$seed$;`);
lines.push("");

// ---------------------------------------------------------------------------
// Plant backfill for variants without plant_id
// ---------------------------------------------------------------------------
lines.push("-- Assign plants to variants that have none (deterministic from product_id)");
lines.push(`do $plants$
declare
  r record;
  v_plant bigint;
  v_plants bigint[];
begin
  select array_agg(id order by id) into v_plants
  from public.store_plant
  where deleted_at is null;
  if v_plants is null or cardinality(v_plants) = 0 then
    raise exception 'Нет производственных площадок для сида';
  end if;

  for r in
    select id, product_id
    from public.store_product_variant
    where deleted_at is null and plant_id is null
  loop
    -- Prefer plant from sibling variant of the same product, else hash product_id
    select plant_id into v_plant
    from public.store_product_variant
    where product_id = r.product_id and plant_id is not null and deleted_at is null
    order by id
    limit 1;

    if v_plant is null then
      v_plant := v_plants[1 + ((r.product_id * 17) % cardinality(v_plants))];
    end if;

    update public.store_product_variant
    set plant_id = v_plant
    where id = r.id;
  end loop;
end;
$plants$;`);
lines.push("");

// ---------------------------------------------------------------------------
// Supply costs (~5–15%, ~20% of pairs omitted)
// ---------------------------------------------------------------------------
lines.push("-- Supply costs: ~5–15% for ~80% of variant×region pairs");
lines.push(`do $supply$
declare
  v record;
  r record;
  v_seed text;
  v_hash bigint;
  v_skip boolean;
  v_pct numeric;
begin
  for v in
    select id from public.store_product_variant where deleted_at is null
  loop
    for r in
      select id, code from public.store_region where deleted_at is null and active
    loop
      v_seed := v.id::text || ':' || lower(r.code);
      -- FNV-ish hash in SQL via hashtext
      v_hash := abs(hashtext(v_seed)::bigint);
      v_skip := (v_hash % 100) < 20;
      if v_skip then
        continue;
      end if;
      v_pct := 5 + ((v_hash / 100) % 101) * 0.1; -- 5.0 .. 15.0
      insert into public.store_product_supply_cost (product_variant_id, region_id, percent)
      values (v.id, r.id, round(v_pct, 1))
      on conflict (product_variant_id, region_id) do update set percent = excluded.percent;
    end loop;
  end loop;
end;
$supply$;`);
lines.push("");

lines.push("commit;");
lines.push("");

writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outPath}`);
console.log(`Products with logistics: ${snapshot.products.length}; containers: ${snapshot.containers.length}`);
