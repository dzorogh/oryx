-- 0. Capture balances for self-validation
-- ---------------------------------------------------------------------------
create table logistics_balance_before as
select
  product_id,
  location_type,
  location_id,
  stock_state,
  customer_order_id,
  customer_order_line_id,
  quantity
from public.logistics_stock_balance;

