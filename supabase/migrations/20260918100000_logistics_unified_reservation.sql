-- ---------------------------------------------------------------------------
-- 3. Posted immutability + line ownership validation
-- ---------------------------------------------------------------------------
create or replace function public.logistics_reservation_enforce_draft_only()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'DELETE' then
    if old.status = 'posted' then
      raise exception 'Posted reservations are immutable';
    end if;
    return old;
  end if;
  if old.status = 'posted' then
    raise exception 'Posted reservations are immutable';
  end if;
  return new;
end;
$$;

create trigger logistics_reservation_immutable_posted
  before update or delete on public.logistics_reservation
  for each row execute function public.logistics_reservation_enforce_draft_only();

create or replace function public.logistics_reservation_line_guard()
returns trigger
language plpgsql
as $$
declare
  v_doc public.logistics_reservation%rowtype;
  v_order_id bigint;
begin
  if tg_op = 'DELETE' then
    select * into strict v_doc from public.logistics_reservation where id = old.reservation_id;
    if v_doc.status = 'posted' then
      raise exception 'Posted reservations are immutable';
    end if;
    return old;
  end if;

  select * into strict v_doc from public.logistics_reservation where id = new.reservation_id;
  if v_doc.status = 'posted' then
    raise exception 'Posted reservations are immutable';
  end if;

  select order_id into v_order_id
  from public.logistics_customer_order_line
  where id = new.customer_order_line_id;
  if v_order_id is null then
    raise exception 'Unknown customer order line %', new.customer_order_line_id;
  end if;
  if v_order_id <> v_doc.customer_order_id then
    raise exception 'Reservation line must belong to the customer order';
  end if;

  return new;
end;
$$;

create trigger logistics_reservation_line_guard_trg
  before insert or update or delete on public.logistics_reservation_line
  for each row execute function public.logistics_reservation_line_guard();

-- ---------------------------------------------------------------------------
-- 4. Migrate documents (split multi-location legacy docs)
-- Insert as draft → lines → promote to posted so immutability triggers stay happy.
-- ---------------------------------------------------------------------------
create table logistics_rsv_doc_map (
  legacy_kind text not null,
  legacy_id bigint not null,
  location_type text not null,
  location_id bigint not null,
  new_id bigint not null,
  primary key (legacy_kind, legacy_id, location_type, location_id)
);

create table logistics_rsv_line_map (
  legacy_kind text not null,
  legacy_line_id bigint not null,
  new_line_id bigint not null,
  new_reservation_id bigint not null,
  primary key (legacy_kind, legacy_line_id)
);

do $$
declare
  v_doc record;
  v_loc record;
  v_line record;
  v_new_id bigint;
  v_new_line_id bigint;
  v_final_status text;
begin
  for v_doc in
    select * from public.logistics_reservation_legacy order by id
  loop
    v_final_status := case when v_doc.status = 'posted' then 'posted' else 'draft' end;
    for v_loc in
      select location_type, location_id
      from public.logistics_reservation_line_legacy
      where reservation_id = v_doc.id
      group by location_type, location_id
      order by location_type, location_id
    loop
      insert into public.logistics_reservation (
        customer_order_id, location_type, location_id, operation, status, origin, note, created_at, posted_at
      ) values (
        v_doc.customer_order_id,
        v_loc.location_type,
        v_loc.location_id,
        'reserve',
        'draft',
        'manual',
        '',
        v_doc.created_at,
        null
      )
      returning id into v_new_id;

      insert into logistics_rsv_doc_map (legacy_kind, legacy_id, location_type, location_id, new_id)
      values ('reservation', v_doc.id, v_loc.location_type, v_loc.location_id, v_new_id);

      for v_line in
        select *
        from public.logistics_reservation_line_legacy
        where reservation_id = v_doc.id
          and location_type = v_loc.location_type
          and location_id = v_loc.location_id
        order by id
      loop
        insert into public.logistics_reservation_line (
          reservation_id, customer_order_line_id, quantity
        ) values (
          v_new_id, v_line.customer_order_line_id, v_line.quantity
        )
        returning id into v_new_line_id;

        insert into logistics_rsv_line_map (legacy_kind, legacy_line_id, new_line_id, new_reservation_id)
        values ('reservation', v_line.id, v_new_line_id, v_new_id);
      end loop;

      if v_final_status = 'posted' then
        update public.logistics_reservation
        set status = 'posted',
            posted_at = coalesce(v_doc.posted_at, v_doc.created_at)
        where id = v_new_id;
      end if;
    end loop;
  end loop;
end;
$$;

do $$
declare
  v_doc record;
  v_loc record;
  v_line record;
  v_new_id bigint;
  v_new_line_id bigint;
  v_final_status text;
  v_origin text;
begin
  for v_doc in
    select * from public.logistics_reservation_release_legacy order by id
  loop
    v_final_status := case when v_doc.status = 'posted' then 'posted' else 'draft' end;
    v_origin := case
      when lower(trim(coalesce(v_doc.reason, ''))) in ('order closed', 'order close') then 'order_close'
      else 'manual'
    end;
    for v_loc in
      select location_type, location_id
      from public.logistics_reservation_release_line_legacy
      where release_id = v_doc.id
      group by location_type, location_id
      order by location_type, location_id
    loop
      insert into public.logistics_reservation (
        customer_order_id, location_type, location_id, operation, status, origin, note, created_at, posted_at
      ) values (
        v_doc.customer_order_id,
        v_loc.location_type,
        v_loc.location_id,
        'release',
        'draft',
        v_origin,
        coalesce(v_doc.reason, ''),
        v_doc.created_at,
        null
      )
      returning id into v_new_id;

      insert into logistics_rsv_doc_map (legacy_kind, legacy_id, location_type, location_id, new_id)
      values ('reservation_release', v_doc.id, v_loc.location_type, v_loc.location_id, v_new_id);

      for v_line in
        select *
        from public.logistics_reservation_release_line_legacy
        where release_id = v_doc.id
          and location_type = v_loc.location_type
          and location_id = v_loc.location_id
        order by id
      loop
        insert into public.logistics_reservation_line (
          reservation_id, customer_order_line_id, quantity
        ) values (
          v_new_id, v_line.customer_order_line_id, v_line.quantity
        )
        returning id into v_new_line_id;

        insert into logistics_rsv_line_map (legacy_kind, legacy_line_id, new_line_id, new_reservation_id)
        values ('reservation_release', v_line.id, v_new_line_id, v_new_id);
      end loop;

      if v_final_status = 'posted' then
        update public.logistics_reservation
        set status = 'posted',
            posted_at = coalesce(v_doc.posted_at, v_doc.created_at)
        where id = v_new_id;
      end if;
    end loop;
  end loop;
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. Remap ledger source identity (quantities untouched)
-- ---------------------------------------------------------------------------
update public.logistics_stock_transaction t
set
  source_type = 'reservation',
  source_id = m.new_reservation_id,
  source_line_id = m.new_line_id
from logistics_rsv_line_map m
where t.source_type = 'reservation'
  and m.legacy_kind = 'reservation'
  and t.source_line_id = m.legacy_line_id;

update public.logistics_stock_transaction t
set
  source_type = 'reservation',
  source_id = m.new_reservation_id,
  source_line_id = m.new_line_id
from logistics_rsv_line_map m
where t.source_type = 'reservation_release'
  and m.legacy_kind = 'reservation_release'
  and t.source_line_id = m.legacy_line_id;

-- Fallback when source_line_id is null: match legacy doc + location
update public.logistics_stock_transaction t
set
  source_type = 'reservation',
  source_id = d.new_id
from logistics_rsv_doc_map d
where t.source_type in ('reservation', 'reservation_release')
  and (
    (t.source_type = 'reservation' and d.legacy_kind = 'reservation')
    or (t.source_type = 'reservation_release' and d.legacy_kind = 'reservation_release')
  )
  and t.source_id = d.legacy_id
  and t.location_type = d.location_type
  and t.location_id = d.location_id
  and not exists (
    select 1 from public.logistics_reservation r where r.id = t.source_id and r.id = d.new_id
  )
  and not exists (
    select 1 from public.logistics_reservation r where r.id = t.source_id
  );

-- Remap customer_order_close free/reserved movements onto order_close Reservations
with close_lines as (
  select
    r.customer_order_id,
    r.location_type,
    r.location_id,
    l.customer_order_line_id,
    r.id as reservation_id,
    l.id as reservation_line_id
  from public.logistics_reservation r
  join public.logistics_reservation_line l on l.reservation_id = r.id
  where r.operation = 'release' and r.origin = 'order_close'
)
update public.logistics_stock_transaction t
set
  source_type = 'reservation',
  source_id = c.reservation_id,
  source_line_id = c.reservation_line_id
from close_lines c
where t.source_type = 'customer_order_close'
  and t.source_id = c.customer_order_id
  and t.location_type = c.location_type
  and t.location_id = c.location_id
  and t.customer_order_line_id = c.customer_order_line_id
  and t.stock_state in ('reserved', 'free');

-- Synthesize order_close Reservations for any remaining close ledger rows
do $$
declare
  v_groups record;
  v_res_id bigint;
  v_line_id bigint;
begin
  for v_groups in
    select
      customer_order_id,
      location_type,
      location_id,
      customer_order_line_id,
      abs(sum(case when stock_state = 'reserved' then quantity else 0 end)) as qty,
      min(posted_at) as posted_at
    from public.logistics_stock_transaction
    where source_type = 'customer_order_close'
      and stock_state in ('reserved', 'free')
      and customer_order_id is not null
      and customer_order_line_id is not null
    group by 1, 2, 3, 4
    having abs(sum(case when stock_state = 'reserved' then quantity else 0 end)) > 0
  loop
    select r.id into v_res_id
    from public.logistics_reservation r
    where r.customer_order_id = v_groups.customer_order_id
      and r.location_type = v_groups.location_type
      and r.location_id = v_groups.location_id
      and r.operation = 'release'
      and r.origin = 'order_close'
    order by r.id
    limit 1;

    if v_res_id is null then
      insert into public.logistics_reservation (
        customer_order_id, location_type, location_id, operation, status, origin, note, created_at, posted_at
      ) values (
        v_groups.customer_order_id,
        v_groups.location_type,
        v_groups.location_id,
        'release',
        'draft',
        'order_close',
        'Order closed',
        v_groups.posted_at,
        null
      )
      returning id into v_res_id;
    end if;

    select l.id into v_line_id
    from public.logistics_reservation_line l
    where l.reservation_id = v_res_id
      and l.customer_order_line_id = v_groups.customer_order_line_id;

    if v_line_id is null then
      -- Parent may already be posted from a previous group at this location
      if exists (select 1 from public.logistics_reservation where id = v_res_id and status = 'posted') then
        update public.logistics_reservation set status = 'draft', posted_at = null where id = v_res_id;
      end if;
      insert into public.logistics_reservation_line (
        reservation_id, customer_order_line_id, quantity
      ) values (
        v_res_id, v_groups.customer_order_line_id, greatest(v_groups.qty, 0.0000001)
      )
      returning id into v_line_id;
    end if;

    update public.logistics_reservation
    set status = 'posted', posted_at = coalesce(posted_at, v_groups.posted_at, now())
    where id = v_res_id and status = 'draft';

    update public.logistics_stock_transaction t
    set
      source_type = 'reservation',
      source_id = v_res_id,
      source_line_id = v_line_id
    where t.source_type = 'customer_order_close'
      and t.source_id = v_groups.customer_order_id
      and t.location_type = v_groups.location_type
      and t.location_id = v_groups.location_id
      and t.customer_order_line_id = v_groups.customer_order_line_id
      and t.stock_state in ('reserved', 'free');
  end loop;
end;
$$;

do $$
begin
  if exists (
    select 1 from public.logistics_stock_transaction where source_type = 'reservation_release'
  ) then
    raise exception 'Migration left reservation_release ledger rows';
  end if;
  if exists (
    select 1
    from public.logistics_stock_transaction t
    where t.source_type = 'reservation'
      and not exists (select 1 from public.logistics_reservation r where r.id = t.source_id)
  ) then
    raise exception 'Migration left reservation ledger rows without matching documents';
  end if;
end;
$$;

