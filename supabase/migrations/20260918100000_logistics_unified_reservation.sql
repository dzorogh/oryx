-- ---------------------------------------------------------------------------
-- 2. New canonical tables
-- ---------------------------------------------------------------------------
create table public.logistics_reservation (
  id bigint generated by default as identity primary key,
  customer_order_id bigint not null references public.logistics_customer_order (id),
  location_type text not null,
  location_id bigint not null,
  operation text not null,
  status text not null default 'draft',
  origin text not null default 'manual',
  note text not null default '',
  created_at timestamptz not null default now(),
  posted_at timestamptz,
  constraint logistics_reservation_location_type_check
    check (location_type in ('warehouse', 'production_order_line', 'transfer')),
  constraint logistics_reservation_operation_check
    check (operation in ('reserve', 'release')),
  constraint logistics_reservation_status_check
    check (status in ('draft', 'posted')),
  constraint logistics_reservation_origin_check
    check (origin in ('manual', 'order_close')),
  constraint logistics_reservation_posted_at_check
    check (status <> 'posted' or posted_at is not null)
);

create table public.logistics_reservation_line (
  id bigint generated by default as identity primary key,
  reservation_id bigint not null references public.logistics_reservation (id) on delete cascade,
  customer_order_line_id bigint not null references public.logistics_customer_order_line (id),
  quantity numeric not null,
  constraint logistics_reservation_line_quantity_check check (quantity > 0),
  constraint logistics_reservation_line_unique unique (reservation_id, customer_order_line_id)
);

create index logistics_reservation_order_idx on public.logistics_reservation (customer_order_id);
create index logistics_reservation_location_idx on public.logistics_reservation (location_type, location_id);
create index logistics_reservation_operation_idx on public.logistics_reservation (operation);
create index logistics_reservation_line_order_line_idx on public.logistics_reservation_line (customer_order_line_id);

alter table public.logistics_reservation enable row level security;
alter table public.logistics_reservation_line enable row level security;

create policy logistics_reservation_all on public.logistics_reservation
  for all to anon, authenticated using (true) with check (true);
create policy logistics_reservation_line_all on public.logistics_reservation_line
  for all to anon, authenticated using (true) with check (true);

