create or replace view public.logistics_stock_balance as
select
  product_id,
  location_type,
  location_id,
  stock_state,
  customer_order_id,
  customer_order_line_id,
  sum(quantity) as quantity
from public.logistics_stock_transaction
group by 1, 2, 3, 4, 5, 6
having abs(sum(quantity)) > 0.0000001;

grant select on public.logistics_stock_balance to anon, authenticated, service_role;

create or replace function public.logistics_code(p_kind text, p_id bigint)
returns text
language sql
immutable
as $$
  select case p_kind
    when 'product' then 'PRD-' || p_id
    when 'manufacturer' then 'PLT-' || p_id
    when 'warehouse' then 'WH-' || p_id
    when 'customer_order' then 'OMS-' || p_id
    when 'production_order' then 'PO-' || p_id
    when 'reservation' then 'RSV-' || p_id
    when 'reservation_release' then 'REL-' || p_id
    when 'transfer' then 'TR-' || p_id
    when 'shipment' then 'SHP-' || p_id
    when 'output' then 'OUT-' || p_id
    when 'return' then 'RET-' || p_id
    when 'customer_order_line' then 'COL-' || p_id
    when 'production_order_line' then 'POL-' || p_id
    when 'reservation_line' then 'RSVL-' || p_id
    when 'reservation_release_line' then 'RELL-' || p_id
    when 'transfer_line' then 'TRL-' || p_id
    when 'transfer_allocation' then 'TRA-' || p_id
    when 'shipment_line' then 'SHL-' || p_id
    when 'output_line' then 'OUTL-' || p_id
    when 'output_allocation' then 'OUA-' || p_id
    when 'return_line' then 'RETL-' || p_id
    when 'product_manufacturer' then 'PM-' || p_id
    when 'stock_transaction' then 'TXN-' || p_id
    when 'setting' then 'SET-' || p_id
    else p_kind || '-' || p_id
  end;
$$;

grant execute on function public.logistics_code(text, bigint) to anon, authenticated, service_role;
