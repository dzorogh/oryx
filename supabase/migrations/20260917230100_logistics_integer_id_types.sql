-- Convert remapped text ids to bigint identity columns and restore FKs.

alter table public.logistics_transfer drop constraint if exists logistics_transfer_check;

do $$
declare
  r record;
begin
  for r in
    select table_name, column_name
    from information_schema.columns
    where table_schema = 'public'
      and table_name like 'logistics_%'
      and table_name <> 'logistics_stock_balance'
      and data_type = 'text'
      and (
        column_name = 'id'
        or column_name = 'transaction_id'
        or (
          column_name like '%_id'
          and column_name not in ('operation_id')
        )
      )
  loop
    execute format(
      'alter table public.%I alter column %I type bigint using %I::bigint',
      r.table_name, r.column_name, r.column_name
    );
  end loop;
end
$$;

do $$
declare
  r record;
  has_rows boolean;
  current_max bigint;
begin
  for r in
    select c.relname as table_name, a.attname as column_name
    from pg_index i
    join pg_class c on c.oid = i.indrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum = any(i.indkey)
    where n.nspname = 'public'
      and c.relname like 'logistics_%'
      and c.relkind = 'r'
      and i.indisprimary
  loop
    execute format(
      'alter table public.%I alter column %I add generated by default as identity',
      r.table_name, r.column_name
    );
    execute format('select exists(select 1 from public.%I)', r.table_name) into has_rows;
    execute format('select coalesce(max(%I), 1) from public.%I', r.column_name, r.table_name) into current_max;
    perform setval(
      pg_get_serial_sequence(format('public.%I', r.table_name), r.column_name),
      current_max,
      has_rows
    );
  end loop;
end
$$;

