-- Helper to copy snapshot fields from product + manufacturer
create or replace function public.store_line_snapshot_fields(p_product_id bigint)
returns table (
  product_name text,
  product_sku text,
  product_unit text,
  manufacturer_id bigint,
  manufacturer_name text,
  manufacturer_code text
)
language sql
stable
as $f$
  select
    p.name,
    p.sku,
    p.unit,
    p.manufacturer_id,
    m.name,
    case when m.id is null then null else public.store_code('manufacturer', m.id) end
  from public.store_product p
  left join public.store_manufacturer m on m.id = p.manufacturer_id
  where p.id = p_product_id;
$f$;

create or replace function public.store_insert_line_region_snapshots(p_line_id bigint, p_product_id bigint)
returns void
language plpgsql
as $f$
declare
  r record;
begin
  for r in
    select
      reg.id as region_id,
      public.store_code('region', reg.id) as region_code,
      reg.name as region_name,
      o.purchase_price, o.purchase_currency,
      o.dealer_price, o.dealer_currency,
      o.retail_price, o.retail_currency,
      o.dealer_status, o.retail_status
    from public.store_region reg
    left join public.store_product_region_offer o
      on o.region_id = reg.id and o.product_id = p_product_id
    order by reg.id
  loop
    insert into public.store_document_product_line_region_snapshot (
      line_id, region_id, region_code, region_name,
      purchase_price, purchase_currency,
      dealer_price, dealer_currency,
      retail_price, retail_currency,
      dealer_status, retail_status
    ) values (
      p_line_id, r.region_id, r.region_code, r.region_name,
      r.purchase_price, r.purchase_currency,
      r.dealer_price, r.dealer_currency,
      r.retail_price, r.retail_currency,
      r.dealer_status, r.retail_status
    );
  end loop;
end;
$f$;

create or replace function public.store_add_document_product_line(
  p_document_id bigint,
  p_product_id bigint,
  p_quantity numeric,
  p_from_owner_type text default null,
  p_from_owner_id bigint default null,
  p_to_owner_type text default null,
  p_to_owner_id bigint default null
)
returns bigint
language plpgsql
as $f$
declare
  v_line_id bigint;
  v_snap record;
begin
  if coalesce(p_quantity, 0) <= 0 then
    raise exception 'Количество должно быть больше нуля';
  end if;
  if p_product_id is null then
    raise exception 'Укажите товар';
  end if;
  perform public.store_assert_owner(p_from_owner_type, p_from_owner_id);
  perform public.store_assert_owner(p_to_owner_type, p_to_owner_id);

  select * into v_snap from public.store_line_snapshot_fields(p_product_id);
  if v_snap.product_name is null then
    raise exception 'Неизвестный товар %', p_product_id;
  end if;

  insert into public.store_document_product_line (
    document_id, product_id, manufacturer_id, quantity,
    from_owner_type, from_owner_id, to_owner_type, to_owner_id,
    product_name, product_sku, product_unit, variant,
    manufacturer_name, manufacturer_code
  ) values (
    p_document_id, p_product_id, v_snap.manufacturer_id, p_quantity,
    nullif(btrim(coalesce(p_from_owner_type, '')), ''), p_from_owner_id,
    nullif(btrim(coalesce(p_to_owner_type, '')), ''), p_to_owner_id,
    v_snap.product_name, v_snap.product_sku, v_snap.product_unit, null,
    v_snap.manufacturer_name, v_snap.manufacturer_code
  )
  returning id into v_line_id;

  perform public.store_insert_line_region_snapshots(v_line_id, p_product_id);
  return v_line_id;
end;
$f$;

grant execute on function public.store_add_document_product_line(bigint, bigint, numeric, text, bigint, text, bigint)
