  l.shipment_id, l.product_id, p.manufacturer_id, l.quantity,
  case
    when s.from_location_type = 'warehouse' then 'order'
    else l.to_owner_type
  end,
  case
    when s.from_location_type = 'warehouse' then s.customer_order_id
    else l.to_owner_id
  end,
  l.to_owner_type, l.to_owner_id,
  p.name, p.sku, p.unit, null,
  m.name, case when m.id is null then null else public.store_code('manufacturer', m.id) end
