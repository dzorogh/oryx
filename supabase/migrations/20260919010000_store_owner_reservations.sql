  from public.store_stock_transaction
  where product_id = p_product_id
    and location_type = p_location_type
    and location_id = p_location_id
    and stock_state = p_stock_state
    and owner_type is not distinct from p_owner_type
    and owner_id is not distinct from p_owner_id;
$$;

