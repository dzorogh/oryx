create or replace function public.store_post_shipment(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_shipment%rowtype;
  v_line public.store_shipment_line%rowtype;
  v_order_line public.store_customer_order_line%rowtype;
  v_op text := 'shipment:' || p_id || ':post';
  v_shipped numeric;
begin
  select * into strict v_doc from public.store_shipment where id = p_id;
  if v_doc.status = 'posted' then
    return 'posted';
  end if;
  if v_doc.status = 'cancelled' then
    raise exception 'Cancelled documents cannot be posted';
  end if;

  for v_line in select * from public.store_shipment_line where shipment_id = p_id
  loop
    select * into v_order_line
    from public.store_customer_order_line
    where order_id = v_doc.customer_order_id and product_id = v_line.product_id;
    if v_order_line.id is null then
      raise exception 'Shipment line must match the single customer order';
    end if;
    v_shipped := public.store_shipped_for_owner_product('order', v_doc.customer_order_id, v_line.product_id);
    if v_shipped + v_line.quantity > v_order_line.quantity then
      raise exception 'Cannot ship more than the ordered quantity';
    end if;
    perform public.store_move(
      v_line.product_id, v_line.quantity,
      'warehouse', v_doc.warehouse_id, 'customer_order', v_doc.customer_order_id,
      'reserved', 'shipped',
      'order', v_doc.customer_order_id,
      'order', v_doc.customer_order_id,
      'shipment', p_id, v_line.id, v_op, v_op || ':' || v_line.id
    );
  end loop;

  update public.store_shipment
  set status = 'posted', posted_at = now()
  where id = p_id;
  return 'posted';
end;
$$;

create or replace function public.store_post_return(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_return%rowtype;
  v_ship public.store_shipment%rowtype;
  v_line public.store_return_line%rowtype;
  v_ship_line public.store_shipment_line%rowtype;
  v_already numeric;
  v_op text := 'shipment_return:' || p_id || ':post';
begin
  select * into strict v_doc from public.store_return where id = p_id;
  if v_doc.status = 'posted' then
    return 'posted';
  end if;
  if v_doc.status = 'cancelled' then
    raise exception 'Cancelled documents cannot be posted';
  end if;
  select * into strict v_ship from public.store_shipment where id = v_doc.shipment_id;
