create or replace function public.store_reservation_line_guard()
returns trigger
language plpgsql
as $$
declare
  v_doc public.store_reservation%rowtype;
begin
  if tg_op = 'DELETE' then
    select * into strict v_doc from public.store_reservation where id = old.reservation_id;
    if v_doc.status = 'posted' then
      raise exception 'Posted reservations are immutable';
    end if;
    return old;
  end if;

  select * into strict v_doc from public.store_reservation where id = new.reservation_id;
  if v_doc.status = 'posted' then
    raise exception 'Posted reservations are immutable';
  end if;
  if new.quantity <= 0 then
    raise exception 'Quantity must be positive';
  end if;
  if public.store_owners_equal(new.from_owner_type, new.from_owner_id, v_doc.to_owner_type, v_doc.to_owner_id) then
    raise exception 'Reservation cannot move quantity to the same owner';
  end if;
  if v_doc.to_owner_type is null and new.from_owner_type is null then
    raise exception 'Reservation cannot move free to free';
  end if;
  perform public.store_assert_owner(new.from_owner_type, new.from_owner_id);
  return new;
end;
$$;

