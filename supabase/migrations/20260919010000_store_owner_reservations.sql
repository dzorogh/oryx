create or replace function public.store_write_tx(
  p_product_id bigint,
  p_quantity numeric,
  p_location_type text,
  p_location_id bigint,
  p_stock_state text,
  p_owner_type text,
  p_owner_id bigint,
  p_source_type text,
  p_source_id bigint,
  p_source_line_id bigint,
  p_operation_id text,
  p_idempotency_key text,
  p_reverses_transaction_id bigint default null,
  p_occurred_at timestamptz default now()
)
returns bigint
language plpgsql
as $$
declare
  v_existing bigint;
  v_id bigint;
  v_unit text;
begin
  perform public.store_assert_owner(p_owner_type, p_owner_id);

  select transaction_id into v_existing
  from public.store_stock_transaction
  where idempotency_key = p_idempotency_key;
  if v_existing is not null then
    return v_existing;
  end if;

  select unit into v_unit from public.store_product where id = p_product_id;
  if v_unit is null then
    raise exception 'Unknown product %', p_product_id;
  end if;

  insert into public.store_stock_transaction (
    occurred_at, posted_at, product_id, unit, quantity,
    location_type, location_id, stock_state, owner_type, owner_id,
    source_type, source_id, source_line_id, operation_id, idempotency_key, reverses_transaction_id
  ) values (
    p_occurred_at, now(), p_product_id, v_unit, p_quantity,
    p_location_type, p_location_id, p_stock_state, p_owner_type, p_owner_id,
    p_source_type, p_source_id, p_source_line_id, p_operation_id, p_idempotency_key, p_reverses_transaction_id
  ) returning transaction_id into v_id;
  return v_id;
end;
$$;

create or replace function public.store_move(
  p_product_id bigint,
  p_quantity numeric,
  p_from_type text,
  p_from_id bigint,
  p_to_type text,
  p_to_id bigint,
  p_from_state text,
  p_to_state text,
  p_from_owner_type text,
  p_from_owner_id bigint,
  p_to_owner_type text,
  p_to_owner_id bigint,
  p_source_type text,
  p_source_id bigint,
  p_source_line_id bigint,
  p_operation_id text,
  p_key_prefix text
)
returns void
language plpgsql
as $$
begin
  if p_quantity <= 0 then
    raise exception 'Quantity must be positive';
  end if;
  if public.store_qty(
    p_product_id, p_from_type, p_from_id, p_from_state, p_from_owner_type, p_from_owner_id
  ) < p_quantity then
    raise exception 'Not enough stock for % %', p_from_state, p_product_id;
  end if;

  perform public.store_write_tx(
    p_product_id, -p_quantity, p_from_type, p_from_id, p_from_state,
    p_from_owner_type, p_from_owner_id, p_source_type, p_source_id, p_source_line_id,
    p_operation_id, p_key_prefix || ':minus'
  );
  perform public.store_write_tx(
    p_product_id, p_quantity, p_to_type, p_to_id, p_to_state,
    p_to_owner_type, p_to_owner_id, p_source_type, p_source_id, p_source_line_id,
    p_operation_id, p_key_prefix || ':plus'
  );
end;
$$;

