    select id into v_line_id
    from public.store_transfer_line
    where transfer_id = p_id and product_id = r.product_id
    limit 1;

    perform public.store_move(
      r.product_id, r.qty,
      'transfer', p_id, 'warehouse', v_doc.to_warehouse_id,
      r.stock_state, r.stock_state,
      r.owner_type, r.owner_id,
      r.owner_type, r.owner_id,
      'transfer_complete', p_id, v_line_id, v_op,
      v_op || ':' || r.product_id || ':' || r.stock_state || ':' || coalesce(r.owner_id::text, 'free')
    );
  end loop;

  update public.store_transfer
  set status = 'delivered'
  where id = p_id;
  return 'delivered';
end;
$$;

create or replace function public.store_complete_output(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_output%rowtype;
  v_order public.store_production_order%rowtype;
  v_mfr public.store_manufacturer%rowtype;
  v_line public.store_output_line%rowtype;
  v_prod_line public.store_production_order_line%rowtype;
  v_already numeric;
  v_remain numeric;
  v_take numeric;
  r record;
  v_op text := 'production_output:' || p_id || ':complete';
begin
  select * into strict v_doc from public.store_output where id = p_id;
  if v_doc.status = 'done' then
    return 'done';
  end if;
  if v_doc.status = 'cancelled' then
    raise exception 'Cancelled outputs cannot be completed';
  end if;
  if exists (
    select 1 from public.store_stock_transaction
    where source_type = 'production_output' and source_id = p_id
  ) then
    update public.store_output
    set status = 'done', done_at = coalesce(done_at, now())
    where id = p_id;
    return 'done';
  end if;
  select * into strict v_order from public.store_production_order where id = v_doc.production_order_id;
  if v_order.status in ('closed', 'cancelled') then
    raise exception 'Cannot output from a closed production order';
  end if;
  select * into strict v_mfr from public.store_manufacturer where id = v_order.manufacturer_id;

  for v_line in select * from public.store_output_line where output_id = p_id
  loop
    select * into strict v_prod_line
    from public.store_production_order_line
    where id = v_line.production_order_line_id;
    if v_prod_line.product_id <> v_line.product_id then
      raise exception 'Output product must match the production order line';
    end if;
    select coalesce(sum(ol.quantity), 0) into v_already
    from public.store_output_line ol
    join public.store_output o on o.id = ol.output_id
    where ol.production_order_line_id = v_line.production_order_line_id
      and o.status = 'done';
    if v_already + v_line.quantity > v_prod_line.quantity then
      raise exception 'Cannot output more than the production order line';
    end if;

    v_remain := v_line.quantity;

    for r in
      select owner_type, owner_id, sum(quantity) as qty
      from public.store_stock_transaction
      where location_type = 'production_order_line'
        and location_id = v_prod_line.id
        and product_id = v_line.product_id
        and stock_state = 'reserved'
      group by 1, 2
      having sum(quantity) > 0
      order by owner_type, owner_id
    loop
      exit when v_remain <= 0;
      v_take := least(r.qty, v_remain);
      perform public.store_move(
        v_line.product_id, v_take,
        'production_order_line', v_prod_line.id, 'warehouse', v_mfr.warehouse_id,
        'reserved', 'reserved',
        r.owner_type, r.owner_id,
        r.owner_type, r.owner_id,
        'production_output', p_id, v_line.id, v_op,
        v_op || ':rsv:' || coalesce(r.owner_type, 'none') || ':' || coalesce(r.owner_id::text, 'none')
      );
      v_remain := v_remain - v_take;
    end loop;

    if v_remain > 0 then
      perform public.store_move(
        v_line.product_id, v_remain,
        'production_order_line', v_prod_line.id, 'warehouse', v_mfr.warehouse_id,
        'free', 'free', null, null, null, null,
        'production_output', p_id, v_line.id, v_op, v_op || ':free:' || v_line.id
      );
    end if;
  end loop;

  update public.store_output
  set status = 'done', done_at = now()
  where id = p_id;
  return 'done';
end;
$$;

create or replace function public.store_reverse_source(p_source_type text, p_source_id bigint)
returns void
language plpgsql
as $$
declare
  r record;
  v_op text := p_source_type || ':' || p_source_id || ':cancel';
begin
  for r in
    select *
    from public.store_stock_transaction
    where source_type = p_source_type
      and source_id = p_source_id
      and reverses_transaction_id is null
      and transaction_id not in (
        select reverses_transaction_id
        from public.store_stock_transaction
        where reverses_transaction_id is not null
      )
    order by posted_at, transaction_id
  loop
    perform public.store_write_tx(
      r.product_id, -r.quantity, r.location_type, r.location_id, r.stock_state,
      r.owner_type, r.owner_id, r.source_type, r.source_id, r.source_line_id,
      v_op, r.idempotency_key || ':rev', r.transaction_id
    );
  end loop;
end;
$$;

create or replace function public.store_sync_production_activation(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_order public.store_production_order%rowtype;
  v_line public.store_production_order_line%rowtype;
  v_delta numeric;
  v_op text := 'production_activation:' || p_id || ':sync';
begin
  select * into strict v_order from public.store_production_order where id = p_id;
  if v_order.status in ('cancelled', 'closed') then
    return v_order.status;
  end if;

  for v_line in select * from public.store_production_order_line where order_id = p_id
  loop
    v_delta := v_line.quantity - v_line.activated_quantity;
    if v_delta > 0 then
      perform public.store_write_tx(
        v_line.product_id, v_delta, 'production_order_line', v_line.id, 'free',
        null, null, 'production_activation', p_id, v_line.id,
        v_op, v_op || ':' || v_line.id || ':' || (v_line.activated_quantity + v_delta)::text
      );
      update public.store_production_order_line
      set activated_quantity = activated_quantity + v_delta
      where id = v_line.id;
    elsif v_delta < 0 then
      if public.store_qty(
        v_line.product_id, 'production_order_line', v_line.id, 'free', null, null
      ) < -v_delta then
        raise exception 'Not enough unused production quantity to reduce the line';
      end if;
      perform public.store_write_tx(
        v_line.product_id, v_delta, 'production_order_line', v_line.id, 'free',
        null, null, 'production_activation', p_id, v_line.id,
        v_op, v_op || ':' || v_line.id || ':down:' || v_line.quantity::text
      );
      update public.store_production_order_line
      set activated_quantity = v_line.quantity
      where id = v_line.id;
    end if;
  end loop;
  return v_order.status;
end;
$$;

create or replace function public.store_cancel_document(p_kind text, p_id bigint)
returns text
language plpgsql
as $$
begin
  if p_kind in ('reservation', 'reservation_release') then
    raise exception 'Posted reservations cannot be cancelled. Create a Reservation that releases to Free instead.';
  elsif p_kind = 'shipment' then
    if exists (select 1 from public.store_shipment where id = p_id and status = 'posted') then
      perform public.store_reverse_source('shipment', p_id);
    end if;
    update public.store_shipment set status = 'cancelled', cancelled_at = now() where id = p_id;
  elsif p_kind = 'shipment_return' then
    if exists (select 1 from public.store_return where id = p_id and status = 'posted') then
      perform public.store_reverse_source('shipment_return', p_id);
    end if;
    update public.store_return set status = 'cancelled', cancelled_at = now() where id = p_id;
  elsif p_kind = 'production_output' then
    if exists (select 1 from public.store_output where id = p_id and status = 'done') then
      perform public.store_reverse_source('production_output', p_id);
    end if;
    update public.store_output set status = 'cancelled', cancelled_at = now() where id = p_id;
  elsif p_kind = 'transfer' then
    if exists (select 1 from public.store_transfer where id = p_id and status = 'delivered') then
      raise exception 'Delivered transfers are kept as history';
    end if;
    if exists (select 1 from public.store_transfer where id = p_id and status = 'sent') then
      perform public.store_reverse_source('transfer_send', p_id);
    end if;
    update public.store_transfer set status = 'cancelled', cancelled_at = now() where id = p_id;
  else
    raise exception 'Unknown document kind %', p_kind;
  end if;
  return 'cancelled';
end;
$$;

