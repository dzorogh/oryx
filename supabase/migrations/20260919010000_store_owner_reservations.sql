create or replace function public.store_assert_owner(p_type text, p_id bigint)
returns void
language plpgsql
stable
as $$
begin
  if p_type is null and p_id is null then
    return;
  end if;
  if p_type is null or p_id is null then
    raise exception 'Owner type and id must both be set or both be empty';
  end if;
  if p_type not in ('order', 'region') then
    raise exception 'Owner type must be order or region';
  end if;
  if p_type = 'order' and not exists (select 1 from public.store_customer_order where id = p_id) then
    raise exception 'Unknown customer order %', p_id;
  end if;
  if p_type = 'region' and not exists (select 1 from public.store_region where id = p_id) then
    raise exception 'Unknown region %', p_id;
  end if;
end;
$$;

create or replace function public.store_owners_equal(p_a_type text, p_a_id bigint, p_b_type text, p_b_id bigint)
returns boolean
language sql
immutable
as $$
  select p_a_type is not distinct from p_b_type and p_a_id is not distinct from p_b_id;
$$;

