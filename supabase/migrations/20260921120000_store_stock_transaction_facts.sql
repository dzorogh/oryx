    if v_shipped + v_line.quantity > v_order_line.quantity then
      raise exception 'Cannot ship more than the ordered quantity';
    end if;
    perform public.store_move(
      v_line.product_id, v_line.quantity,
      'warehouse', v_doc.warehouse_id, 'customer_order', v_doc.customer_order_id,
      'order', v_doc.customer_order_id,
      'order', v_doc.customer_order_id,
      'shipment', p_id
    );
  end loop;

  update public.store_shipment set status = 'posted' where id = p_id;
  return 'posted';
end;
$$;

create or replace function public.store_post_return(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_return%rowtype;
  v_ship public.store_shipment%rowtype;
  v_line public.store_return_line%rowtype;
  v_ship_line public.store_shipment_line%rowtype;
  v_already numeric;
begin
  select * into strict v_doc from public.store_return where id = p_id;
  if v_doc.status = 'posted' then
    return 'posted';
  end if;
  if v_doc.status = 'cancelled' then
    raise exception 'Cancelled documents cannot be posted';
  end if;
  select * into strict v_ship from public.store_shipment where id = v_doc.shipment_id;
  if v_ship.status <> 'posted' then
    raise exception 'Return requires a posted shipment';
  end if;

  for v_line in select * from public.store_return_line where return_id = p_id
  loop
    select * into strict v_ship_line from public.store_shipment_line where id = v_line.shipment_line_id;
    select coalesce(sum(rl.quantity), 0) into v_already
    from public.store_return_line rl
    join public.store_return r on r.id = rl.return_id
    where rl.shipment_line_id = v_line.shipment_line_id
      and r.status = 'posted'
      and r.id <> p_id;
    if v_already + v_line.quantity > v_ship_line.quantity then
      raise exception 'Return cannot exceed the shipped quantity';
    end if;
    perform public.store_move(
      v_ship_line.product_id, v_line.quantity,
      'customer_order', v_ship.customer_order_id, 'warehouse', v_ship.warehouse_id,
      'order', v_ship.customer_order_id,
      null, null,
      'return', p_id
    );
  end loop;

  update public.store_return set status = 'posted' where id = p_id;
  return 'posted';
end;
$$;

create or replace function public.store_send_transfer(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_transfer%rowtype;
  v_line public.store_transfer_line%rowtype;
  v_alloc public.store_transfer_allocation%rowtype;
  v_allocated numeric;
  v_free numeric;
begin
  select * into strict v_doc from public.store_transfer where id = p_id;
  if v_doc.status in ('sent', 'delivered') then
    return v_doc.status;
  end if;
  if v_doc.status = 'cancelled' then
    raise exception 'Cancelled documents cannot be posted';
  end if;

  for v_line in select * from public.store_transfer_line where transfer_id = p_id
  loop
    select coalesce(sum(quantity), 0) into v_allocated
    from public.store_transfer_allocation
    where line_id = v_line.id;
    if v_allocated > v_line.quantity then
      raise exception 'Allocated quantity cannot exceed the document line';
    end if;
    v_free := v_line.quantity - v_allocated;

    for v_alloc in select * from public.store_transfer_allocation where line_id = v_line.id
    loop
      perform public.store_assert_owner(v_alloc.owner_type, v_alloc.owner_id);
      perform public.store_move(
        v_line.product_id, v_alloc.quantity,
        'warehouse', v_doc.from_warehouse_id, 'transfer', p_id,
        v_alloc.owner_type, v_alloc.owner_id,
        v_alloc.owner_type, v_alloc.owner_id,
        'transfer', p_id
      );
    end loop;

    if v_free > 0 then
      perform public.store_move(
        v_line.product_id, v_free,
        'warehouse', v_doc.from_warehouse_id, 'transfer', p_id,
        null, null, null, null,
        'transfer', p_id
      );
    end if;
  end loop;

  update public.store_transfer set status = 'sent' where id = p_id;
  return 'sent';
end;
$$;

