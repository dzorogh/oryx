create or replace function public.store_record_document_history(
  p_document_type text,
  p_document_id bigint,
  p_event_type text,
  p_status text,
  p_expected_end_on date,
  p_created_at timestamptz default now(),
  p_created_by bigint default public.store_current_user_id()
)
returns bigint
language plpgsql
as $$
declare
  v_id bigint;
begin
  if p_document_type not in (
    'reservation', 'shipment', 'return', 'transfer',
    'production_order', 'output', 'customer_order'
  ) then
    raise exception 'Unknown document type %', p_document_type;
  end if;
  if p_event_type not in ('created', 'status_changed', 'expected_end_changed') then
    raise exception 'Unknown history event %', p_event_type;
  end if;
  insert into public.store_document_history (
    document_type, document_id, event_type, status, expected_end_on, created_at, created_by
  ) values (
    p_document_type, p_document_id, p_event_type, p_status, p_expected_end_on,
    coalesce(p_created_at, now()), coalesce(p_created_by, public.store_current_user_id())
  )
  returning id into v_id;
  return v_id;
end;
$$;

grant execute on function public.store_record_document_history(text, bigint, text, text, date, timestamptz, bigint)
  to anon, authenticated, service_role;

