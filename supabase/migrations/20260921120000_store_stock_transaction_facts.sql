create or replace function public.store_document_history_trigger()
returns trigger
language plpgsql
as $$
declare
  v_type text;
  v_expected date;
begin
  v_type := case tg_table_name
    when 'store_customer_order' then 'customer_order'
    when 'store_production_order' then 'production_order'
    when 'store_reservation' then 'reservation'
    when 'store_transfer' then 'transfer'
    when 'store_shipment' then 'shipment'
    when 'store_output' then 'output'
    when 'store_return' then 'return'
    else null
  end;
  if v_type is null then
    return new;
  end if;

  v_expected := case
    when tg_table_name in (
      'store_customer_order', 'store_production_order', 'store_transfer', 'store_output'
    ) then new.expected_end_on
    else null
  end;

  if tg_op = 'INSERT' then
    perform public.store_record_document_history(
      v_type, new.id, 'created', new.status, v_expected, new.created_at, new.created_by
    );
    return new;
  end if;

  if new.status is distinct from old.status then
    perform public.store_record_document_history(
      v_type, new.id, 'status_changed', new.status, v_expected, now(), public.store_current_user_id()
    );
  end if;

  if tg_table_name in (
    'store_customer_order', 'store_production_order', 'store_transfer', 'store_output'
  ) and new.expected_end_on is distinct from old.expected_end_on then
    perform public.store_record_document_history(
      v_type, new.id, 'expected_end_changed', new.status, v_expected, now(), public.store_current_user_id()
    );
  end if;

  return new;
end;
$$;

