language plpgsql
as $$
declare
  v_id bigint;
begin
  if p_quantity = 0 then
    raise exception 'Quantity must not be zero';
  end if;
  if p_location_type not in ('warehouse', 'production_order', 'transfer', 'customer_order') then
    raise exception 'Location type % is not allowed', p_location_type;
  end if;
  if p_document_type not in (
    'reservation', 'shipment', 'return', 'transfer', 'production_order', 'output'
  ) then
    raise exception 'Document type % is not allowed', p_document_type;
  end if;
  perform public.store_assert_owner(p_assigned_to_type, p_assigned_to_id);
  if p_location_type = 'customer_order' then
    if p_assigned_to_type is distinct from 'order' or p_assigned_to_id is distinct from p_location_id then
      raise exception 'Customer order location must be assigned to the same order';
    end if;
  end if;
  if not exists (select 1 from public.store_product where id = p_product_id) then
    raise exception 'Unknown product %', p_product_id;
  end if;

  insert into public.store_stock_transaction (
    created_at, product_id, quantity,
    location_type, location_id, assigned_to_type, assigned_to_id,
    document_type, document_id
  ) values (
    now(), p_product_id, p_quantity,
    p_location_type, p_location_id, p_assigned_to_type, p_assigned_to_id,
    p_document_type, p_document_id
  )
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.store_move(
  p_product_id bigint,
  p_quantity numeric,
  p_from_type text,
  p_from_id bigint,
  p_to_type text,
  p_to_id bigint,
  p_from_assigned_type text,
  p_from_assigned_id bigint,
  p_to_assigned_type text,
  p_to_assigned_id bigint,
  p_document_type text,
  p_document_id bigint
)
returns void
language plpgsql
as $$
begin
  if p_quantity <= 0 then
    raise exception 'Quantity must be positive';
  end if;
  if public.store_qty(
    p_product_id, p_from_type, p_from_id, p_from_assigned_type, p_from_assigned_id
  ) < p_quantity then
    raise exception 'Not enough stock for %', p_product_id;
  end if;

  perform public.store_write_tx(
    p_product_id, -p_quantity, p_from_type, p_from_id,
    p_from_assigned_type, p_from_assigned_id, p_document_type, p_document_id
  );
  perform public.store_write_tx(
    p_product_id, p_quantity, p_to_type, p_to_id,
    p_to_assigned_type, p_to_assigned_id, p_document_type, p_document_id
  );
end;
$$;

create or replace function public.store_post_reservation(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_reservation%rowtype;
  v_line public.store_reservation_line%rowtype;
  v_order_line public.store_customer_order_line%rowtype;
  v_open numeric;
begin
  select * into strict v_doc from public.store_reservation where id = p_id;
  if v_doc.status = 'posted' then
    return 'posted';
  end if;
  if v_doc.location_type not in ('warehouse', 'production_order', 'transfer') then
    raise exception 'Reservation location type % is not allowed', v_doc.location_type;
  end if;
  if not exists (select 1 from public.store_reservation_line where reservation_id = p_id) then
    raise exception 'Reservation % has no lines', p_id;
  end if;
  perform public.store_assert_owner(v_doc.to_owner_type, v_doc.to_owner_id);

  for v_line in
    select * from public.store_reservation_line where reservation_id = p_id order by id
  loop
    if public.store_owners_equal(
      v_line.from_owner_type, v_line.from_owner_id, v_doc.to_owner_type, v_doc.to_owner_id
    ) then
      raise exception 'Reservation cannot move quantity to the same owner';
    end if;
    if v_doc.to_owner_type is null and v_line.from_owner_type is null then
      raise exception 'Reservation cannot move free to free';
    end if;

    if v_doc.to_owner_type = 'order' then
      select * into v_order_line
      from public.store_customer_order_line
      where order_id = v_doc.to_owner_id and product_id = v_line.product_id;
      if v_order_line.id is null then
        raise exception 'Customer order does not contain this product';
      end if;
      v_open := v_order_line.quantity
        - public.store_shipped_for_owner_product('order', v_doc.to_owner_id, v_line.product_id)
        - public.store_reserved_for_owner_product('order', v_doc.to_owner_id, v_line.product_id);
      if v_line.quantity > v_open then
        raise exception 'Cannot reserve more than the open customer order quantity';
      end if;
    end if;

    perform public.store_move(
      v_line.product_id, v_line.quantity,
      v_doc.location_type, v_doc.location_id, v_doc.location_type, v_doc.location_id,
      v_line.from_owner_type, v_line.from_owner_id,
      v_doc.to_owner_type, v_doc.to_owner_id,
      'reservation', p_id
    );
  end loop;

  update public.store_reservation set status = 'posted' where id = p_id;
  return 'posted';
end;
$$;

create or replace function public.store_close_customer_order(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_loc record;
  v_line record;
  v_res_id bigint;
begin
  if exists (select 1 from public.store_customer_order where id = p_id and status = 'closed') then
    return 'closed';
  end if;

  for v_loc in
    select location_type, location_id
    from public.store_stock_transaction
    where assigned_to_type = 'order' and assigned_to_id = p_id and location_type <> 'customer_order'
    group by 1, 2
    having sum(quantity) > 0
    order by 1, 2
  loop
    insert into public.store_reservation (
      location_type, location_id, to_owner_type, to_owner_id, status, origin, note
    ) values (
      v_loc.location_type, v_loc.location_id, null, null, 'draft', 'order_close', 'Order closed'
    )
    returning id into v_res_id;

    for v_line in
      select product_id, sum(quantity) as qty
      from public.store_stock_transaction
      where assigned_to_type = 'order'
        and assigned_to_id = p_id
        and location_type = v_loc.location_type
        and location_id = v_loc.location_id
      group by 1
      having sum(quantity) > 0
      order by 1
    loop
      insert into public.store_reservation_line (
        reservation_id, product_id, quantity, from_owner_type, from_owner_id
      ) values (
        v_res_id, v_line.product_id, v_line.qty, 'order', p_id
      );
    end loop;

    perform public.store_post_reservation(v_res_id);
  end loop;

  update public.store_customer_order set status = 'closed' where id = p_id;
  return 'closed';
end;
$$;

create or replace function public.store_close_production_order(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_hold record;
  v_line record;
  v_res_id bigint;
  r record;
begin
  if exists (select 1 from public.store_production_order where id = p_id and status = 'closed') then
    return 'closed';
  end if;

  for v_hold in
    select assigned_to_type, assigned_to_id
    from public.store_stock_transaction
    where location_type = 'production_order'
      and location_id = p_id
      and assigned_to_type is not null
    group by 1, 2
    having sum(quantity) > 0
    order by 1, 2
  loop
    insert into public.store_reservation (
      location_type, location_id, to_owner_type, to_owner_id, status, origin, note
    ) values (
      'production_order', p_id, null, null, 'draft', 'order_close', 'Production order closed'
    )
    returning id into v_res_id;

    for v_line in
      select product_id, sum(quantity) as qty
      from public.store_stock_transaction
      where location_type = 'production_order'
        and location_id = p_id
        and assigned_to_type is not distinct from v_hold.assigned_to_type
        and assigned_to_id is not distinct from v_hold.assigned_to_id
      group by 1
      having sum(quantity) > 0
      order by 1
    loop
      insert into public.store_reservation_line (
        reservation_id, product_id, quantity, from_owner_type, from_owner_id
      ) values (
        v_res_id, v_line.product_id, v_line.qty, v_hold.assigned_to_type, v_hold.assigned_to_id
      );
    end loop;

    perform public.store_post_reservation(v_res_id);
  end loop;

  if exists (
    select 1
    from public.store_stock_transaction
    where location_type = 'production_order'
      and location_id = p_id
      and assigned_to_type is not null
    group by product_id, assigned_to_type, assigned_to_id
    having sum(quantity) > 0
  ) then
    raise exception 'Cannot close a production order while reserved quantity remains';
  end if;

  for r in
    select product_id, assigned_to_type, assigned_to_id, sum(quantity) as qty
    from public.store_stock_transaction
    where location_type = 'production_order' and location_id = p_id
    group by 1, 2, 3
    having sum(quantity) > 0
  loop
    perform public.store_write_tx(
      r.product_id, -r.qty, 'production_order', p_id,
      r.assigned_to_type, r.assigned_to_id,
      'production_order', p_id
    );
  end loop;

  update public.store_production_order set status = 'closed' where id = p_id;
  return 'closed';
end;
$$;

create or replace function public.store_post_shipment(p_id bigint)
returns text
language plpgsql
as $$
declare
  v_doc public.store_shipment%rowtype;
  v_line public.store_shipment_line%rowtype;
  v_order_line public.store_customer_order_line%rowtype;
  v_shipped numeric;
