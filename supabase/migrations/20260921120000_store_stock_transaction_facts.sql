select
  t.transaction_id,
  t.posted_at,
  t.product_id,
  t.quantity,
  case when t.location_type = 'production_order_line' then 'production_order' else t.location_type end,
  case
    when t.location_type = 'production_order_line' then (
      select pol.order_id from public.store_production_order_line pol where pol.id = t.location_id
    )
    else t.location_id
  end,
  t.owner_type,
  t.owner_id,
  case t.source_type
    when 'reservation' then 'reservation'
    when 'shipment' then 'shipment'
    when 'shipment_return' then 'return'
    when 'transfer_send' then 'transfer'
    when 'transfer_complete' then 'transfer'
    when 'production_activation' then 'production_order'
    when 'production_close' then 'production_order'
    when 'production_output' then 'output'
    else t.source_type
  end,
  t.source_id
from public.store_stock_transaction t;

