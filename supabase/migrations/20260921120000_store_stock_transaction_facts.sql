begin;

-- ---------------------------------------------------------------------------
-- 0. Preflight holes + snapshot balances (remapped PO line → parent PO)
-- ---------------------------------------------------------------------------
do $$
begin
  if exists (
    select 1 from public.store_stock_transaction
    where reverses_transaction_id is not null or quantity = 0
  ) then
    raise exception 'Journal contains reversals or zero quantities';
  end if;
  if exists (
    select 1 from public.store_stock_transaction t
    where t.location_type = 'production_order_line'
      and not exists (select 1 from public.store_production_order_line pol where pol.id = t.location_id)
  ) then
    raise exception 'Journal production_order_line location has no parent line';
  end if;
  if exists (
    select 1 from public.store_reservation r
    where r.location_type = 'production_order_line'
      and not exists (select 1 from public.store_production_order_line pol where pol.id = r.location_id)
  ) then
    raise exception 'Reservation production_order_line location has no parent line';
  end if;
  if exists (select 1 from public.store_reservation where status = 'posted' and posted_at is null)
    or exists (select 1 from public.store_shipment where status = 'posted' and posted_at is null)
    or exists (select 1 from public.store_return where status = 'posted' and posted_at is null)
    or exists (select 1 from public.store_transfer where status in ('sent', 'delivered') and sent_at is null)
    or exists (select 1 from public.store_output where status = 'done' and done_at is null)
    or exists (select 1 from public.store_customer_order where status = 'closed' and closed_at is null)
    or exists (select 1 from public.store_production_order where status = 'closed' and closed_at is null)
    or exists (select 1 from public.store_shipment where status = 'cancelled' and cancelled_at is null)
    or exists (select 1 from public.store_return where status = 'cancelled' and cancelled_at is null)
    or exists (select 1 from public.store_transfer where status = 'cancelled' and cancelled_at is null)
    or exists (select 1 from public.store_output where status = 'cancelled' and cancelled_at is null)
  then
    raise exception 'Document lifecycle timestamp hole';
  end if;
end;
$$;

create table public.store_fact_balance_before as
select
  t.product_id,
  case when t.location_type = 'production_order_line' then 'production_order' else t.location_type end as location_type,
  case
    when t.location_type = 'production_order_line' then (
      select pol.order_id from public.store_production_order_line pol where pol.id = t.location_id
    )
    else t.location_id
  end as location_id,
  t.owner_type as assigned_to_type,
  t.owner_id as assigned_to_id,
  sum(t.quantity) as quantity
from public.store_stock_transaction t
group by 1, 2, 3, 4, 5
having abs(sum(t.quantity)) > 0.0000001;

